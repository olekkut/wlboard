#[allow(clippy::too_many_arguments)]
fn make_layout(
    code: &str,
    short_label: &str,
    display_name: &str,
    xkb_name: &str,
    is_rtl: bool,
    grave: (&str, &str),
    digits_shift: [&str; 12],
    top: [(&str, &str); 13],
    home: [(&str, &str); 11],
    bottom: [(&str, &str); 10],
    altgr_entries: &[(&str, &str, &str)],
    compact_counts: (usize, usize, usize),
) -> LayoutDefinition {
    let mut altgr_map = HashMap::new();
    for &(k, n, s) in altgr_entries {
        altgr_map.insert(
            k.to_owned(),
            PairLabel {
                normal: n.to_owned(),
                shift: s.to_owned(),
            },
        );
    }

    let build_row = |codes: &[&str], pairs: &[(&str, &str)]| -> Vec<CharKeyDef> {
        codes
            .iter()
            .zip(pairs.iter())
            .map(|(c, (n, s))| {
                let ag = altgr_map.get(*c);
                CharKeyDef {
                    code: (*c).to_owned(),
                    normal: (*n).to_owned(),
                    shift: (*s).to_owned(),
                    altgr: ag.map(|p| p.normal.clone()),
                    altgr_shift: ag.map(|p| p.shift.clone()),
                }
            })
            .collect()
    };

    let compact_rows = vec![
        TOP_CODES[..compact_counts.0.min(12)]
            .iter()
            .map(|s| (*s).to_owned())
            .collect(),
        HOME_CODES[..compact_counts.1.min(11)]
            .iter()
            .map(|s| (*s).to_owned())
            .collect(),
        BOTTOM_CODES[..compact_counts.2.min(10)]
            .iter()
            .map(|s| (*s).to_owned())
            .collect(),
    ];

    LayoutDefinition {
        code: code.to_owned(),
        short_label: short_label.to_owned(),
        display_name: display_name.to_owned(),
        xkb_name: xkb_name.to_owned(),
        is_rtl,
        grave: PairLabel {
            normal: grave.0.to_owned(),
            shift: grave.1.to_owned(),
        },
        digits_shift: digits_shift.iter().map(|s| (*s).to_owned()).collect(),
        top_row: build_row(&TOP_CODES, &top),
        home_row: build_row(&HOME_CODES, &home),
        bottom_row: build_row(&BOTTOM_CODES, &bottom),
        compact_rows,
        altgr: altgr_map,
    }
}

